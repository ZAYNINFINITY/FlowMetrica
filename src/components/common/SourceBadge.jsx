import { useId, useState } from 'react';
import {
  Activity,
  Cpu,
  FileText,
  FlaskConical,
  Info,
  Network,
  ShieldCheck,
  Sparkles,
} from 'lucide-react';

/**
 * Provenance labels are contractual: docs/UI-UX-SPEC.md fixes the exact copy.
 * Every entry also carries an icon and a note, so status is never colour-only.
 */
const SOURCE_LABELS = {
  live_matlab_execution: {
    label: 'Live MATLAB Result',
    Icon: Cpu,
    tone: 'border-ok/40 bg-ok/10 text-ok',
    note: 'Calculated live by MATLAB during this request.',
  },
  matlab_fixture: {
    label: 'Saved MATLAB Result',
    Icon: Cpu,
    tone: 'border-ok/40 bg-ok/10 text-ok',
    note: 'Generated by MATLAB and stored locally.',
  },
  reference_verified_fixture: {
    label: 'Saved Result · Reference-Verified',
    Icon: ShieldCheck,
    tone: 'border-accent/40 bg-accent/10 text-accent',
    note: 'Calculated by the independent reference implementation and cross-checked. MATLAB export is pending, so this is not a live MATLAB result.',
  },
  live_measurement: {
    label: 'Live Network Measurement',
    Icon: Activity,
    tone: 'border-ok/40 bg-ok/10 text-ok',
    note: 'Measured from the current connection.',
  },
  live_network_measurement: {
    label: 'Live Network Measurement',
    Icon: Activity,
    tone: 'border-ok/40 bg-ok/10 text-ok',
    note: 'Measured from the current connection and solved by the shared execution interface.',
  },
  simulated_data: {
    label: 'Simulated Network Scenario',
    Icon: Network,
    tone: 'border-warn/40 bg-warn/10 text-warn',
    note: 'A teaching model. It is not a measurement of a real network.',
  },
  ai_proposed: {
    label: 'AI-Proposed Model',
    Icon: Sparkles,
    tone: 'border-warn/40 bg-warn/10 text-warn',
    note: 'A proposal only. It is not a verified mathematical result.',
  },
  template_generated: {
    label: 'Template-Based Report',
    Icon: FileText,
    tone: 'border-analysis/40 bg-analysis/10 text-analysis',
    note: 'Assembled locally from verified values and fixed wording. No AI service was contacted.',
  },
};

export default function SourceBadge({ source, className = '' }) {
  const [noteOpen, setNoteOpen] = useState(false);
  const noteId = useId();
  const item = SOURCE_LABELS[source] ?? {
    label: 'Result source unknown',
    Icon: FlaskConical,
    tone: 'border-line bg-raised text-muted',
    note: 'The result did not include a provenance label.',
  };
  const { Icon } = item;

  return (
    <span
      className={`relative inline-flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-[11px] font-semibold ${item.tone} ${className}`}
      title={item.note}
    >
      <Icon aria-hidden="true" className="h-3.5 w-3.5" />
      <span>
        <span className="sr-only">Result provenance: </span>
        {item.label}
      </span>
      <button
        type="button"
        aria-label={`Why this label: ${item.note}`}
        aria-expanded={noteOpen}
        aria-controls={noteId}
        onClick={() => setNoteOpen((current) => !current)}
        className="-mr-1 rounded-full p-0.5 opacity-70 transition-opacity hover:opacity-100 focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-current"
      >
        <Info aria-hidden="true" className="h-3 w-3" />
      </button>
      {noteOpen && (
        <span
          id={noteId}
          role="note"
          className="absolute left-0 top-full z-40 mt-1 w-max max-w-[260px] whitespace-normal rounded-lg border border-line bg-raised p-2 text-left text-[11px] font-normal normal-case leading-snug text-muted shadow-panel"
        >
          {item.note}
        </span>
      )}
    </span>
  );
}
